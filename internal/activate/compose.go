package activate

import (
	"fmt"
	"path/filepath"
	"sort"
	"strings"
)

const ComposePath = "/etc/katzenpost/kno-compose.yaml"

type composeService struct {
	Name      string
	Container string
	Image     string
	Ports     []string
	Dir       string
}

func Compose(tag string, svcs []composeService) string {
	var b strings.Builder
	fmt.Fprintf(&b, "# Generated by kno for release %s. Do not edit.\n", tag)
	fmt.Fprintf(&b, "# The source is this network's service manifests; edit those and\n")
	fmt.Fprintf(&b, "# run 'kno activate' again. Local edits here are overwritten.\n")
	b.WriteString("services:\n")

	sorted := append([]composeService{}, svcs...)
	sort.Slice(sorted, func(i, j int) bool { return sorted[i].Name < sorted[j].Name })
	for _, s := range sorted {
		fmt.Fprintf(&b, "  %s:\n", yamlKey(s.Name))
		fmt.Fprintf(&b, "    image: %s\n", yamlStr(s.Image))

		b.WriteString("    pull_policy: never\n")
		fmt.Fprintf(&b, "    container_name: %s\n", yamlStr(s.Container))
		fmt.Fprintf(&b, "    hostname: %s\n", yamlStr(s.Container))

		b.WriteString("    restart: unless-stopped\n")
		if len(s.Ports) > 0 {
			b.WriteString("    ports:\n")
			for _, p := range s.Ports {
				fmt.Fprintf(&b, "      - %s\n", yamlStr(p))
			}
		}
		b.WriteString("    volumes:\n")
		for _, v := range []string{
			s.Dir + "/conf:/conf",
			s.Dir + "/data:/var/lib/katzenpost",
			s.Dir + "/logs:/var/log/katzenpost",
		} {
			fmt.Fprintf(&b, "      - %s\n", yamlStr(v))
		}
	}
	return b.String()
}

func ComposePorts(field string) []string {
	var out []string
	f := strings.Fields(field)
	for i := 0; i < len(f); i++ {
		switch f[i] {
		case "-p", "--publish":
			if i+1 < len(f) {
				out = append(out, f[i+1])
				i++
			}
		default:
			if v, ok := strings.CutPrefix(f[i], "--publish="); ok {
				out = append(out, v)
			}
		}
	}
	return out
}

func yamlStr(s string) string {
	s = strings.ReplaceAll(s, `\`, `\\`)
	s = strings.ReplaceAll(s, `"`, `\"`)
	return `"` + s + `"`
}

func yamlKey(s string) string { return yamlStr(s) }

func composeGuard(svc string, vals map[string]string) error {
	names := make([]string, 0, len(vals))
	for k := range vals {
		names = append(names, k)
	}
	sort.Strings(names)
	for _, k := range names {
		if strings.ContainsAny(vals[k], "\n\r") {
			return fmt.Errorf("docker service %s has a %s containing a newline;"+
				" it is rendered into a compose file and cannot be quoted safely", svc, k)
		}
	}
	return nil
}

func composeDirOf(dir string) string { return filepath.Clean(dir) }
